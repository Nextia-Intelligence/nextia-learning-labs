/** Québec typography: a no-break space (U+00A0) before : ; ! ? (and none twice). */
export function frTypography(s: string): string {
  return s.replace(/[  ]?([:;!?])(?=\s|$|<|")/g, " $1");
}

const DICTS: Record<Lang, Record<Key, string>> = {
  en,
  fr: Object.fromEntries(Object.entries(fr).map(([k, v]) => [k, frTypography(v)])) as Record<Key, string>,
};

export function translate(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  const text = DICTS[lang][key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`));
}

export function hasKey(key: string): key is Key {
  return key in en;
}

